import {test,expect} from '@playwright/test';
const token=process.env.DMEM_E2E_TOKEN||'automated-smoke-token-not-production';
async function connect(page:import('@playwright/test').Page){
 await page.goto('/');
 await page.getByLabel('Library connection token').fill(token);
 await page.getByRole('button',{name:'Open library'}).click();
 await expect(page.getByRole('heading',{name:'Template library.'})).toBeVisible();
}
test('real library → import → selected evidence → edit → revision → export → reopen',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 const docTitle='Demo Meeting Notes '+Date.now();
 await connect(page);
 await expect(page.locator('.template-card').filter({hasText:'Public template'}).getByRole('button',{name:'Meeting Notes and Action Items preview'})).toBeVisible();
 await page.screenshot({path:'test-results/library-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'My references',exact:true}).click();
 const fixtureName='project-fixture-'+Date.now();
 await page.getByLabel('Upload reference file').setInputFiles({name:fixtureName+'.md',mimeType:'text/markdown',buffer:Buffer.from('# Project decisions\nThe beta review is scheduled for 15 November.\nThe owner is synthetic user A.')});
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.getByRole('dialog').getByText('The beta review is scheduled for 15 November.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Close',exact:true}).click();
 await page.getByRole('button',{name:'Template library',exact:true}).click();
 await page.locator('.template-card').filter({hasText:'Public template'}).getByRole('button',{name:'Meeting Notes and Action Items preview'}).click();
 const modal=page.getByRole('dialog');
 await expect(modal.getByRole('heading',{name:'Meeting Notes and Action Items',exact:true})).toBeVisible();
 await modal.getByRole('button',{name:'Copy to my templates',exact:true}).click();
 await expect(modal.getByText('Original: My Document Memory · v1 · CC0-1.0')).toBeVisible();
 await modal.getByLabel('New document title').fill(docTitle);
 await modal.getByRole('checkbox',{name:new RegExp(fixtureName)}).check();
 await modal.getByRole('button',{name:'Use this template'}).click();
 await expect(modal).not.toBeVisible();
 await expect(page.getByLabel('Document title',{exact:true})).toHaveValue(docTitle);
 await expect(page.locator('textarea[aria-label^="Source excerpt"]')).toHaveCount(3);
 const quotes=await page.locator('textarea[aria-label^="Source excerpt"]').evaluateAll(els=>els.map(e=>(e as HTMLTextAreaElement).value));
 expect(quotes.join('\n')).toContain('The beta review is scheduled for 15 November.');
 await page.locator('textarea[aria-label^="Paragraph"]').first().fill('Confirm the scope of the beta review.');
 await expect(page.getByRole('button',{name:'Export ↗'})).toBeDisabled();
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Saved · v2');
 await page.screenshot({path:'test-results/editor-desktop.png',fullPage:true});
 const downloaded=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export ↗'}).click();
 const artifact=await downloaded;expect(artifact.suggestedFilename()).toBe('document.docx');await artifact.saveAs('test-results/verified-document.docx');
 await page.getByRole('button',{name:'Version history',exact:true}).click();
 await page.getByRole('button',{name:new RegExp('v1 · '+docTitle)}).click();
 await expect(page.getByRole('dialog').getByText('{{Needs confirmation: Purpose}}',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Apply this version to draft',exact:true}).click();
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(page.locator('textarea[aria-label^="Paragraph"]').first()).toHaveValue('{{Needs confirmation: Purpose}}');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Saved · v3');
 await page.getByRole('button',{name:'← Library',exact:true}).click();
 await page.getByRole('button',{name:'My documents',exact:true}).click();
 await page.getByRole('button',{name:new RegExp(docTitle+' Document · v3')}).click();
 await expect(page.locator('textarea[aria-label^="Paragraph"]').first()).toHaveValue('{{Needs confirmation: Purpose}}');
 await page.reload();
 await expect(page.getByRole('heading',{name:'Template library.'})).toBeVisible();
 expect(errors).toEqual([]);
});
test('decks require approved outline and remain editable; mobile has no horizontal overflow',async({page})=>{
 await connect(page);
 await page.getByRole('button',{name:'Slides',exact:true}).click();
 await page.getByRole('button',{name:'Startup Pitch Deck preview'}).click();
 const modal=page.getByRole('dialog');const create=modal.getByRole('button',{name:'Use this template'});
 await expect(create).toBeDisabled();
 await modal.getByRole('checkbox',{name:'I approve this slide outline and order.'}).check();
 await modal.getByLabel('New document title').fill('Demo Pitch Deck');
 await create.click();
 await page.getByLabel('Slide title',{exact:true}).fill('Customer Problem');
 await page.getByLabel('Slide body',{exact:true}).fill('Summarize verified customer interviews here.');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Saved · v2');
 const downloaded=page.waitForEvent('download');await page.getByRole('button',{name:'Export ↗'}).click();
 const artifact=await downloaded;expect(artifact.suggestedFilename()).toBe('document.pptx');await artifact.saveAs('test-results/verified-deck.pptx');
 await page.screenshot({path:'test-results/deck-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/deck-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'← Library',exact:true}).click();
 await page.getByRole('button',{name:'Template library',exact:true}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/library-mobile.png',fullPage:true});
});
