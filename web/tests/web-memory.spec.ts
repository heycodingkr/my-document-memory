import {test,expect} from '@playwright/test';
const fixture=process.env.DMEM_WEB_FIXTURE_URL;
test.skip(!fixture,'Requires the isolated web-memory fixture server');
test('preview a public document, choose country, save privately and read provenance',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(token=>sessionStorage.setItem('dmem.token',token),process.env.DMEM_E2E_TOKEN!);
 await page.goto('/#templates');
 await expect(page.getByRole('heading',{name:'Template library.'})).toBeVisible();
 await page.getByText('Import from the web',{exact:false}).first().click();
 await page.getByLabel('Document URL',{exact:true}).fill(fixture+'/pages/resume-ko.html');
 await page.getByRole('button',{name:'Preview URL',exact:true}).click();
 await expect(page.getByRole('region',{name:'Web document preview'})).toBeVisible();
 await page.getByLabel('Import title').fill('Web smoke structure');
 await page.getByLabel('Import locale').selectOption('en-US');
 await page.getByRole('button',{name:'Save privately',exact:true}).click();
 await expect(page.locator('.web-import').getByRole('status')).toContainText('Saved to your private library.');
 const response=await page.request.get('/v1/templates?q=Web%20smoke%20structure',{headers:{Authorization:'Bearer '+process.env.DMEM_E2E_TOKEN}});
 const stored=(await response.json()).items.find((t:{title:string})=>t.title==='Web smoke structure');
 expect(stored.form.locale).toBe('en-US');expect(stored.form.region).toBe('US');
 await page.reload();
 await page.getByRole('button',{name:'Web smoke structure preview',exact:true}).click();
 await expect(page.getByRole('complementary',{name:'Original web source'})).toContainText('CC-BY-4.0');
 await expect(page.getByRole('complementary',{name:'Original web source'})).toContainText('Structure only');
 expect(errors).toEqual([]);
});
test('a Korean import becomes visible in the matching private library language',async({page})=>{
 await page.addInitScript(token=>sessionStorage.setItem('dmem.token',token),process.env.DMEM_E2E_TOKEN!);
 await page.goto('/#templates');
 await page.getByLabel('Visibility',{exact:true}).selectOption('public');
 await page.getByText('Import from the web',{exact:false}).first().click();
 await page.getByLabel('Document URL',{exact:true}).fill(fixture+'/pages/resume-ko.html');
 await page.getByRole('button',{name:'Preview URL',exact:true}).click();
 await page.getByLabel('Import title').fill('Korean web structure');
 await page.getByRole('button',{name:'Save privately',exact:true}).click();
 await expect(page.locator('.web-import').getByRole('status')).toContainText('Saved to your private library.');
 await expect(page.getByLabel('Template language',{exact:true})).toHaveValue('ko-KR');
 await expect(page.getByLabel('Visibility',{exact:true})).toHaveValue('private');
 await expect(page.getByRole('button',{name:'Korean web structure preview',exact:true})).toBeVisible();
});
