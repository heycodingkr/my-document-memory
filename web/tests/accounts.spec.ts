import {test,expect,type Page} from '@playwright/test';
import {readFileSync} from 'node:fs';
const mailbox=process.env.DMEM_E2E_MAILBOX;
const screenshots=process.env.DMEM_E2E_OUTPUT_DIR||'test-results';
test.skip(!mailbox,'Requires isolated synthetic email fixture: python3 tests/smoke/accounts-v1.py');
async function login(page:Page){
 const email='browser-'+Date.now()+'@example.test';
 await page.goto('/#me');
 await page.getByLabel('Email address',{exact:true}).fill(email);
 await page.getByRole('button',{name:'Send sign-in link',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Check your inbox.');
 await expect.poll(()=>{try{return JSON.parse(readFileSync(mailbox!,'utf8')).email;}catch{return '';}}).toBe(email);
 const url=JSON.parse(readFileSync(mailbox!,'utf8')).url;
 await page.goto(url);
 await expect(page).toHaveURL(/\/#me$/);
 await page.getByRole('button',{name:'Continue to my space',exact:true}).click();
 await expect(page.getByRole('heading',{name:'My page.'})).toBeVisible();
 return email;
}
test('ML-02: email links open in another browser, require confirmation and reject replay',async({page,browser})=>{
 const email='portable-'+Date.now()+'@example.test';
 await page.goto('/#me');
 await page.getByLabel('Email address',{exact:true}).fill(email);
 await page.getByRole('button',{name:'Send sign-in link',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Check your inbox.');
 await expect.poll(()=>{try{return JSON.parse(readFileSync(mailbox!,'utf8')).email;}catch{return '';}}).toBe(email);
 const url=JSON.parse(readFileSync(mailbox!,'utf8')).url;
 const other=await browser.newContext();
 try{
  const target=await other.newPage();await target.goto(url);
  await expect(target).toHaveURL(/\/#me$/);
  await expect(target.getByRole('button',{name:'Continue to my space',exact:true})).toBeVisible();
  expect((await target.request.get('/v1/auth/session')).status()).toBe(401);
  await target.getByRole('button',{name:'Continue to my space',exact:true}).click();
  await expect(target.getByText(email,{exact:true})).toBeVisible();
  await target.reload();await expect(target.getByText(email,{exact:true})).toBeVisible();
  await target.getByRole('button',{name:'Sign out',exact:true}).click();
  await target.goto(url);await target.getByRole('button',{name:'Continue to my space',exact:true}).click();
  await expect(target.getByRole('alert')).toContainText('expired or has already been used');
  expect((await target.request.get('/v1/auth/session')).status()).toBe(401);
  await target.getByRole('button',{name:'Send a new sign-in link',exact:true}).click();
  await expect(target.getByLabel('Email address',{exact:true})).toBeVisible();
  await target.screenshot({path:screenshots+'/email-link-sign-in.png'});
 }finally{await other.close();}
});
